// Returns the integer value of a dictionary entry, or a sentinel when absent.
static int
dict_int_(CosDictObjNode *dict, const char *key)
{
    CosObjNode *value = NULL;
    if (!cos_dict_obj_node_get_value_with_string(dict, key, &value, NULL) ||
        !value || !cos_obj_node_is_integer(value)) {
        return -1;
    }
    return cos_int_obj_node_get_value((CosIntObjNode *)value);
}

static int
retains_both_revision_trailers(void)
{
    CosMemoryStream *stream = NULL;
    CosDoc *doc = parse_pdf_bytes_(trailer_chain_pdf, sizeof(trailer_chain_pdf), &stream);
    TEST_EXPECT(doc != NULL);

    // Head is the newest revision (the xref stream); its /Prev links the older classic trailer.
    CosTrailer * const newest = cos_doc_get_trailer(doc);
    TEST_EXPECT(newest != NULL);
    TEST_EXPECT(cos_trailer_get_xref_offset(newest) == R2_OFFSET);

    CosTrailer * const oldest = cos_trailer_get_prev(newest);
    TEST_EXPECT(oldest != NULL);
    TEST_EXPECT(cos_trailer_get_xref_offset(oldest) == R1_OFFSET);
    TEST_EXPECT(cos_trailer_get_prev(oldest) == NULL);

    // Both trailer dictionaries survived and are distinct (newest /Size 3, oldest /Size 2).
    TEST_EXPECT(dict_int_(cos_trailer_get_dict(newest), "Size") == 3);
    TEST_EXPECT(dict_int_(cos_trailer_get_dict(oldest), "Size") == 2);
    TEST_EXPECT(dict_int_(cos_trailer_get_dict(newest), "Prev") == R1_OFFSET);

    cos_doc_destroy(doc);
    cos_stream_close((CosStream *)stream);
    return EXIT_SUCCESS;
}

static int
merges_sections_from_all_revisions(void)
{
    CosMemoryStream *stream = NULL;
    CosDoc *doc = parse_pdf_bytes_(trailer_chain_pdf, sizeof(trailer_chain_pdf), &stream);
    TEST_EXPECT(doc != NULL);

    // Object 1 is described only by the older classic section; object 2 only by the newer xref
    // stream. Both resolving proves the master table merged sections from both revisions.
    CosError error = cos_error_none();
    CosIndirectObjNode *catalog = cos_doc_get_object(doc, cos_obj_id_make(1, 0), &error);
    TEST_EXPECT(catalog != NULL);
    TEST_EXPECT(cos_obj_node_get_type(cos_indirect_obj_node_get_value(catalog)) == CosObjNodeType_Dict);
    cos_obj_node_release((CosObjNode *)catalog);

    error = cos_error_none();
    CosIndirectObjNode *xref_obj = cos_doc_get_object(doc, cos_obj_id_make(2, 0), &error);
    TEST_EXPECT(xref_obj != NULL);
    TEST_EXPECT(cos_obj_node_get_type(cos_indirect_obj_node_get_value(xref_obj)) == CosObjNodeType_Stream);
    cos_obj_node_release((CosObjNode *)xref_obj);

    cos_doc_destroy(doc);
    cos_stream_close((CosStream *)stream);
    return EXIT_SUCCESS;
}

