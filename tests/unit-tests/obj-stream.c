// Returns true if the dictionary's /Type name equals expected_type.
static bool
dict_type_is_(CosObjNode *dict_node,
              const char *expected_type)
{
    if (!dict_node || cos_obj_node_get_type(dict_node) != CosObjNodeType_Dict) {
        return false;
    }

    CosObjNode *type_node = NULL;
    if (!cos_dict_obj_node_get_value_with_string((CosDictObjNode *)dict_node,
                                                 "Type",
                                                 &type_node,
                                                 NULL) ||
        !type_node ||
        cos_obj_node_get_type(type_node) != CosObjNodeType_Name) {
        return false;
    }

    const CosString * const name = cos_name_obj_node_get_value((CosNameObjNode *)type_node);
    const char * const name_str = name ? cos_string_get_data(name) : NULL;
    return name_str && strcmp(name_str, expected_type) == 0;
}

static int
resolves_compressed_catalog(void)
{
    CosMemoryStream *stream = NULL;
    CosDoc *doc = parse_pdf_bytes_(obj_stream_pdf, sizeof(obj_stream_pdf), &stream);
    TEST_EXPECT(doc != NULL);

    // Object 1 is compressed (type 2) inside object stream 2; it is the catalog.
    CosError error = cos_error_none();
    CosObjNode *indirect = cos_doc_get_object(doc, cos_obj_id_make(1, 0), &error);
    TEST_EXPECT(indirect != NULL);
    TEST_EXPECT(error.code == COS_ERROR_NONE);
    TEST_EXPECT(cos_obj_node_get_type(indirect) == CosObjNodeType_Indirect);

    CosObjNode *value = cos_indirect_obj_node_get_value((CosIndirectObjNode *)indirect);
    TEST_EXPECT(dict_type_is_(value, "Catalog"));

    cos_obj_node_release(indirect);
    cos_doc_destroy(doc);
    cos_stream_close((CosStream *)stream);
    return EXIT_SUCCESS;
}

static int
resolves_compressed_pages(void)
{
    CosMemoryStream *stream = NULL;
    CosDoc *doc = parse_pdf_bytes_(obj_stream_pdf, sizeof(obj_stream_pdf), &stream);
    TEST_EXPECT(doc != NULL);

    // Object 3 is the second object in the same object stream; it is the pages node.
    CosError error = cos_error_none();
    CosObjNode *indirect = cos_doc_get_object(doc, cos_obj_id_make(3, 0), &error);
    TEST_EXPECT(indirect != NULL);
    TEST_EXPECT(error.code == COS_ERROR_NONE);

    CosObjNode *value = cos_indirect_obj_node_get_value((CosIndirectObjNode *)indirect);
    TEST_EXPECT(dict_type_is_(value, "Pages"));

    cos_obj_node_release(indirect);
    cos_doc_destroy(doc);
    cos_stream_close((CosStream *)stream);
    return EXIT_SUCCESS;
}

static int
resolves_compressed_root(void)
{
    CosMemoryStream *stream = NULL;
    CosDoc *doc = parse_pdf_bytes_(obj_stream_pdf, sizeof(obj_stream_pdf), &stream);
    TEST_EXPECT(doc != NULL);

    // The /Root reference (1 0 R) points at a compressed object; it must resolve.
    CosObjNode *root = cos_doc_get_root(doc);
    TEST_EXPECT(root != NULL);

    cos_doc_destroy(doc);
    cos_stream_close((CosStream *)stream);
    return EXIT_SUCCESS;
}

static int
repeat_fetch_hits_cache(void)
{
    CosMemoryStream *stream = NULL;
    CosDoc *doc = parse_pdf_bytes_(obj_stream_pdf, sizeof(obj_stream_pdf), &stream);
    TEST_EXPECT(doc != NULL);

    // Two fetches of the same compressed object return the identical cached node.
    CosObjNode *first = cos_doc_get_object(doc, cos_obj_id_make(3, 0), NULL);
    CosObjNode *second = cos_doc_get_object(doc, cos_obj_id_make(3, 0), NULL);
    TEST_EXPECT(first != NULL);
    TEST_EXPECT(first == second);

    cos_obj_node_release(first);
    cos_obj_node_release(second);
    cos_doc_destroy(doc);
    cos_stream_close((CosStream *)stream);
    return EXIT_SUCCESS;
}

static int
extends_is_not_implemented(void)
{
    CosMemoryStream *stream = NULL;
    CosDoc *doc = parse_pdf_bytes_(obj_stream_extends_pdf, sizeof(obj_stream_extends_pdf), &stream);
    TEST_EXPECT(doc != NULL);

    // The object stream carries /Extends, so resolving a compressed object fails cleanly.
    CosError error = cos_error_none();
    CosObjNode *obj = cos_doc_get_object(doc, cos_obj_id_make(1, 0), &error);
    TEST_EXPECT(obj == NULL);
    TEST_EXPECT(error.code == COS_ERROR_NOT_IMPLEMENTED);

    cos_doc_destroy(doc);
    cos_stream_close((CosStream *)stream);
    return EXIT_SUCCESS;
}

