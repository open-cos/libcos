// clang-format on

typedef struct TestFixture {
    CosPredictorFilter *filter;
} TestFixture;

static bool
setup(TestFixture *fixture)
{
    fixture->filter = NULL;
    return true;
}

static void
teardown(TestFixture *fixture)
{
    if (fixture->filter) {
        cos_stream_close((CosStream *)fixture->filter);
        fixture->filter = NULL;
    }
}

// Builds a predictor filter over the encoded bytes, reads it fully in small
// chunks, and checks the reconstruction against the expected bytes.
static bool
run_case(TestFixture *fixture,
         int predictor,
         size_t colors,
         size_t bits_per_component,
         size_t columns,
         const unsigned char *encoded,
         size_t encoded_size,
         const unsigned char *expected,
         size_t expected_size)
{
    fixture->filter = cos_predictor_filter_create_(predictor,
                                                   colors,
                                                   bits_per_component,
                                                   columns,
                                                   NULL);
    if (!fixture->filter) {
        return false;
    }

    CosMemoryStream * const source = cos_memory_stream_create_readonly(encoded, encoded_size);
    if (!source) {
        return false;
    }
    cos_filter_attach_source((CosFilter *)fixture->filter, (CosStream *)source);

    unsigned char output[1024] = {0};
    size_t total = 0;
    while (total < sizeof(output)) {
        size_t want = sizeof(output) - total;
        if (want > 37) {
            want = 37;
        }
        const size_t read_count = cos_stream_read((CosStream *)fixture->filter,
                                                  output + total,
                                                  want,
                                                  NULL);
        if (read_count == 0) {
            break;
        }
        total += read_count;
    }

    return total == expected_size && memcmp(output, expected, expected_size) == 0;
}

